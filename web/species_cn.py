# 通用：分类名转中文（先查对应层级映射，没有则原样返回）
def cn_name(rank, name):
    """rank: 'phylum'/'class'/'ordr'/'family'，name: 英文学名，返回中文名（无映射则原样）"""
    if not name:
        return name
    if rank == "phylum":
        return PHYLUM_CN.get(name, name)
    if rank == "class":
        return CLASS_CN.get(name, name)
    if rank == "ordr":
        return ORDR_CN.get(name, name)
    if rank == "family":
        return FAMILY_CN.get(name, name)
    return name


