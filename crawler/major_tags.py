def tag_majors(text):
    """关键词规则打标：返回命中的标签列表（LLM 失败时的兜底）。"""
    if not text:
        return []
    hits = []
    for tag, kws in MAJOR_KEYWORDS.items():
        if any(k in text for k in kws):
            hits.append(tag)
    return hits
